Deno.serve(async (req) => {
    const base44 = createClientFromRequest(req);
    const user = await base44.auth.me();
    if (!user) {
        return Response.json({ error: 'Unauthorized' }, { status: 401 });
    }

    const { message, history, systemPrompt } = await req.json();

    const apiKey = Deno.env.get('GEMINI_API_KEY');
    if (!apiKey) {
        return Response.json({ error: 'GEMINI_API_KEY not set' }, { status: 500 });
    }

    // Build conversation history for Gemini
    const contents = [];

    if (history && history.length > 0) {
        for (const msg of history) {
            contents.push({
                role: msg.role === 'assistant' ? 'model' : 'user',
                parts: [{ text: msg.content }]
            });
        }
    }

    // הוספת תוכן המסעדה + השאלה
    contents.push({
        role: 'user',
        parts: [{ text: `מידע המסעדה:\n${RESTAURANT_KNOWLEDGE}\n\nשאלה: ${message}` }]
    });

    const fullSystemPrompt = systemPrompt || `אתה דביר - עוזר AI פנימי של מסעדת TOP ALENA.
אתה עונה בעברית בלבד, בצורה קצרה וידידותית.
אתה עוזר לעובדים עם שאלות על נהלי עבודה, תפקידים, לוגיסטיקה, תפריט, ושאלות כלליות.
השתמש במידע המסעדה שסופק כדי לענות על שאלות.
אם המידע לא קיים במסמכים, ענה: "לא מצאתי מידע על זה - בדוק עם המנהל."`;

    const body = {
        system_instruction: { parts: [{ text: fullSystemPrompt }] },
        contents,
        generationConfig: {
            temperature: 0.2,
            maxOutputTokens: 2048,
        }
    };

    const res = await fetch(
        `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`,
        {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify(body)
        }
    );

    const data = await res.json();

    if (!res.ok) {
        return Response.json({ error: data.error?.message || 'Gemini API error' }, { status: 500 });
    }

    const text = data.candidates?.[0]?.content?.parts?.[0]?.text || '';
    return Response.json({ reply: text });
});